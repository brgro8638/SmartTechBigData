"""Run the JavaScript implementation (js/cli.js) through Node.js.

The slice is passed as float64 .npy, so JavaScript gets exactly the same
numbers as Python. Timings are measured inside JavaScript and exclude Node's
start-up time.
"""

import json
import shutil
import subprocess
import tempfile
from pathlib import Path

import numpy as np

CLI = Path(__file__).resolve().parents[2] / "js" / "cli.js"


def node_available():
    return shutil.which("node") is not None


def run_js(img, config, repeats=1, timeout=300):
    """Returns (labels, work_image, result_dict)."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        np.save(tmp / "slice.npy", np.asarray(img, dtype=np.float64))
        # The CLI gets a single slice, so its slice index must be 0
        (tmp / "config.json").write_text(json.dumps({**config, "slice": 0}))
        proc = subprocess.run(
            ["node", str(CLI), str(tmp / "slice.npy"), str(tmp / "config.json"), str(tmp / "out"), str(repeats)],
            capture_output=True, text=True, timeout=timeout)
        if proc.returncode != 0:
            raise RuntimeError(f"Node failed: {proc.stderr.strip()}")
        labels = np.load(tmp / "out" / "labels.npy")
        work = np.load(tmp / "out" / "work.npy")
        result = json.loads((tmp / "out" / "result.json").read_text())
    return labels, work, result


def js_phantom():
    """Phantom generated by the JavaScript code: (volume, ground_truth)."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        config = {"slice": 0, "normalize": {"p_low": 0, "p_high": 100}, "smooth_sigma": 0,
                  "pca": {"enabled": False, "n_components": 1}, "method": "threshold",
                  "threshold": {"mode": "manual", "value": 0.5}}
        (tmp / "config.json").write_text(json.dumps(config))
        subprocess.run(["node", str(CLI), "phantom", str(tmp / "config.json"), str(tmp / "out")],
                       check=True, capture_output=True)
        return np.load(tmp / "out" / "phantom.npy"), np.load(tmp / "out" / "phantom_gt.npy")
